# --- panel (docs/design.md sec 4) ---
PLATE_SIZE_MM = 254.0       # 10 in square, sec 4.1
STOCK_THICKNESS_MM = 36.0   # sec 4.1
# Master scale reference (sec 1.2): one lambda_GW is this many mm on the finished piece, which
# fixes S = SCALE_LAMBDA_MM / lambda_GW[km]. It is independent of the plate size, so the stars,
# separation and every printed part keep their size when the panel is resized; a smaller panel
# simply windows the same field (the 254 mm panel shows 0.85 lambda to the corner).
SCALE_LAMBDA_MM = 150.0 * np.sqrt(2)
A_PP_MM = 20.0                # relief peak-to-valley, sec 4.2. Slope and curvature scale
                              # linearly with it: 36.9 deg max slope (guard: MAX_SLOPE_DEG = 45
                              # in validate.py), 10.4x the ball radius on curvature, 16.7 mm of
                              # wood below the deepest valley and 18 mm behind the post holes
                              # (36 mm stock) against a 3.0 mm minimum (validate.py
                              # MIN_HOLE_CLEARANCE_MM). Re-verify whenever A_pp, Z_EVAL_MM,
                              # C_EFF_FACTOR or STOCK_THICKNESS_MM change (sec 5.1, sec 7); the
                              # star height (STAR_MIN_GAP_MM) depends on them too.

# The field is carved all the way to the panel's cut edge: no edge window or border taper.

# --- field model: retarded per-star Newtonian potential (docs/design.md sec 3) ---
# Each star's own position is retarded self-consistently (a Lienard-Wiechert-like scalar
# potential). The field is finite everywhere except at the two stellar surfaces, so no
# near-zone window is needed.
#
# Z_EVAL_MM: the field is evaluated off the orbital/panel plane, at (x, y, Z_EVAL_MM), rather
# than in-plane at (x, y, 0). This acts as a softening length: it bounds the minimum source
# distance to |Z_EVAL_MM|, which is what controls the dynamic range (in-plane, r -> 0 directly
# under each star and the potential would diverge). Larger magnitudes suppress the near-star
# peaks *and* relax milling slope/curvature together, but push the retardation phase toward a
# near-constant offset dominated by Z_EVAL_MM itself, which washes out the in-plane spiral
# structure if taken too far. -70 mm was chosen by inspection: it is the largest softening
# depth that still reads as a trailing two-armed pattern (docs/design.md sec 3.4).
Z_EVAL_MM = -70.0
RETARDED_ITERS = 10   # fixed-point iterations for the retarded-time solve;
                       # contraction factor is ~(k/2)*d_star ~ 0.18/iteration

# Hypothetical wave speed, applied only to each star's own retardation phase
# (binary.retardation_k_half) -- NOT to the plate/star geometry, which stays fixed at whatever
# scale the real C produced (sec 1.2). Smaller values wind the pattern more tightly.
# Re-verify A_pp against validate.py whenever this changes. Set to 1.0 to recover the real
# speed of light.
C_EFF_FACTOR = 0.35
C_EFF = C * C_EFF_FACTOR

GRID_STEP_MM = 0.5   # plate sampling, sec 8

# --- milling (docs/design.md sec 5) ---
BALL_RADIUS_MM = 3.175 / 2
STEPOVER_MM = 0.75

# --- posts / assembly (docs/design.md sec 7) ---
POST_DIAMETER_MM = 3.175                        # 1/8 in brass rod
SOCKET_CLEARANCE_MM = 0.2                       # diametral clearance + epoxy gap in the star
SOCKET_DIAMETER_MM = POST_DIAMETER_MM + SOCKET_CLEARANCE_MM
SOCKET_DEPTH_MM = 6.0                           # from the pole point; lower half only (star.build_star)
PANEL_HOLE_DEPTH_MM = 8.0                       # drilled from the local relief surface, not z = 0
# Panel hole diameter = POST_DIAMETER_MM (a 1/8 in bit); it is a CAM operation, not modelled in the plate STL.
STAR_CENTER_Z_MM = 3.85   # both stars level; the value that delivers STAR_MIN_GAP_MM (sec 7)
STAR_MIN_GAP_MM = 5.0     # required closest approach of each star's surface to the plate surface;
                          # STAR_CENTER_Z_MM is the level height that delivers it (heavy star
                          # governs). validate.check_star_height enforces it -- re-derive
                          # STAR_CENTER_Z_MM if A_pp, Z_EVAL_MM, C_EFF_FACTOR or the star
                          # shapes change.

# --- star mesh (docs/design.md sec 6.3) ---
ICOSPHERE_SUBDIVISIONS = 6   # 20 * 4^6 = 81,920 faces
