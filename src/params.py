# --- binary system (docs/design.md sec 1.1) ---
M1_MSUN = 1.6   # heavier star
M2_MSUN = 1.2   # lighter star, q = 0.75
R1_KM = 12.0    # heavier star radius
R2_KM = 12.5    # lighter star radius (NS radii are nearly mass-independent)
A_KM = 33.0     # orbital separation, near-contact -- see docs/design.md sec 1.3

# --- tidal deformation ---
# The star surfaces are not set by constants here. The f-mode amplitudes, spin, exaggeration
