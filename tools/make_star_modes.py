"""Generate data/star_modes.toml: per-star f-mode amplitudes at the sculpture snapshot.

Calls tidal_waveform.get_ba_l2 / get_ba_l3 at the sculpture's own f_gw (binary.solve().f_gw)
and writes the *total* complex amplitude (equilibrium + dynamical tide) with the signed
overlaps used to compute it. The shape code (src/tidal_shape.py) reads the .toml.

Stellar model: Gamma = 2 (n = 1) Newtonian polytrope, solved in src/polytrope.py and scaled
to each star through omega_0 = sqrt(G M / R^3). The l=2 nonlinear frequency shift is derived
per star from Paper 1 Eq. 16 (docs/neutron_star_shape.md); l=3 has none.

Run:  python tools/make_star_modes.py [--spin-heavy -500] [--spin-light -200] [--out PATH]
The V11 regime gate (past-resonance error) is applied before anything is written.
"""
import argparse
import sys
import warnings
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

import binary                      # noqa: E402
import params as P                 # noqa: E402
import polytrope as poly           # noqa: E402
import tidal_shape as TS           # noqa: E402
import tidal_waveform as jw        # noqa: E402

# sqrt(pi/5) (J2 + 4 kappa2 I) from Paper 1 Table 1 (J2 = -0.21, kappa2 = -0.45, I = 0.32)
PAPER1_NL = float(np.sqrt(np.pi / 5) * (-0.21 + 4 * (-0.45) * 0.32))     # = -0.623
W_REF = jw.W_NL_REF                                                     # reference GW frequency of the nonlinear shift

STARS = {   # name: (M [Msun], R [km], companion mass [Msun], companion_sign, default spin [Hz])
    "heavy": (P.M1_MSUN, P.R1_KM, P.M2_MSUN, +1, -500.0),
    "light": (P.M2_MSUN, P.R2_KM, P.M1_MSUN, -1, -200.0),
}


def polytrope_numbers():
    out = {}
    for l in (2, 3):
        k_love, k, h = poly.static_love(l)
        w_over_w0 = poly.modes(l, 1)[0][0]
        out[l] = dict(k=k, h=h, w=w_over_w0)
    return out


def star_block(name, poly_nums, spin_hz, f_snap_hz):
    M, R_km, Mc, sign, _ = STARS[name]
    M1, M2, R = M * jw.Ms, Mc * jw.Ms, R_km * 1e5
    Mt = M1 + M2
    w0 = np.sqrt(jw.G * M1 / R ** 3)
    wa2, wa3 = poly_nums[2]["w"] * w0, poly_nums[3]["w"] * w0
    k2, k3 = poly_nums[2]["k"], poly_nums[3]["k"]
    C = jw.G * M1 / (R * jw.c ** 2)
    lam2 = k2 / (1.5 * C ** 5)
    A_nl2 = PAPER1_NL * (M2 / M1) * W_REF ** 2 * R ** 3 / (jw.G * Mt)
    Om_s = 2.0 * np.pi * spin_hz

    ff = np.unique(np.concatenate([np.linspace(60.0, 1.15 * f_snap_hz, 20001), [f_snap_hz]]))
    i = int(np.argmin(np.abs(ff - f_snap_hz)))
    assert ff[i] == f_snap_hz

    with warnings.catch_warnings():
        warnings.simplefilter("error")      # get_ba_l3 warns if the grid starts inside the resonance window
        ba2, _, _, _ = jw.get_ba_l2(ff, M1, M2, R, lam2, wa2, A_nl_1=A_nl2, w_nl_ref=W_REF,
                                    OmegaS1=Om_s, gr_flag=1)
        ba3, _, _, _ = jw.get_ba_l3(ff, M1, M2, R, k3, wa3, A_nl_1=0.0, w_nl_ref=W_REF,
                                    OmegaS1=Om_s, gr_flag=1)
    ba2, ba3 = np.asarray(ba2)[:, i], np.asarray(ba3)[:, i]

    I2 = float(np.sqrt(5.0 * k2 / (4.0 * np.pi)))            # exactly what get_ba_l2 used (same sign, all m)
    I3 = np.asarray(jw.get_overlaps_l3(k3), dtype=float)     # signed, order MM_L3
    modes = []
    for m, c in zip((2, 0, -2), ba2):                         # get_ba_l2 order [+2, 0, -2]
        modes.append(dict(l=2, m=m, C=complex(c), I=I2, h=poly_nums[2]["h"], w=wa2))
    for m, c, I in zip(jw.MM_L3, ba3, I3):
        modes.append(dict(l=3, m=int(m), C=complex(c), I=float(I), h=poly_nums[3]["h"], w=wa3))

    r_over_R = float((jw.G * Mt / (np.pi * f_snap_hz) ** 2) ** (1 / 3) / R)
    star = dict(name=name, M_msun=M, R_km=R_km, Mc_msun=Mc, companion_sign=sign, f_gw_hz=f_snap_hz,
                spin_hz=spin_hz, spin_oblateness=True, X=1.0, X_lag=1.0,
                r_over_R=r_over_R, A_nl_l2=float(A_nl2), omega0_rad_s=float(w0), modes=modes)
    return star


def to_model(star):
    return TS.StarModel(
        name=star["name"], M_msun=star["M_msun"], R_km=star["R_km"], Mc_msun=star["Mc_msun"],
        companion_sign=star["companion_sign"], f_gw_hz=star["f_gw_hz"], spin_hz=star["spin_hz"],
        spin_oblateness=star["spin_oblateness"], X=star["X"], X_lag=star["X_lag"],
        modes=tuple(TS.ModeAmp(m["l"], m["m"], m["C"], m["I"], m["h"], m["w"]) for m in star["modes"]))


def _f(x):
    return repr(float(x))


def write_toml(path, stars, meta):
    lines = ["# Generated by tools/make_star_modes.py -- do not edit by hand.",
             "# Amplitudes are the TOTAL complex b_a (equilibrium + dynamical tide), src/tidal_waveform.py;",
             "# I is the signed overlap used to compute C, so the shape uses C/I mode by mode.",
             "", "[meta]"]
    for k, v in meta.items():
        lines.append(f'{k} = "{v}"' if isinstance(v, str) else f"{k} = {_f(v)}")
    for s in stars:
        lines += ["", "[[star]]", f'name = "{s["name"]}"']
        for k in ("M_msun", "R_km", "Mc_msun"):
            lines.append(f"{k} = {_f(s[k])}")
        lines.append(f"companion_sign = {s['companion_sign']}")
        for k in ("f_gw_hz", "spin_hz"):
            lines.append(f"{k} = {_f(s[k])}")
        lines.append(f"spin_oblateness = {'true' if s['spin_oblateness'] else 'false'}")
        for k in ("X", "X_lag", "r_over_R", "A_nl_l2", "omega0_rad_s"):
            lines.append(f"{k} = {_f(s[k])}")
        for m in s["modes"]:
            lines += ["", "[[star.mode]]", f"l = {m['l']}", f"m = {m['m']}",
                      f"C_re = {_f(m['C'].real)}", f"C_im = {_f(m['C'].imag)}", f"I = {_f(m['I'])}",
                      f"h = {_f(m['h'])}", f"omega_a0_rad_s = {_f(m['w'])}"]
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--spin-heavy", type=float, default=STARS["heavy"][4], help="Hz, negative = anti-aligned")
    ap.add_argument("--spin-light", type=float, default=STARS["light"][4], help="Hz, negative = anti-aligned")
    ap.add_argument("--out", type=Path, default=ROOT / "data" / "star_modes.toml")
    args = ap.parse_args(argv)

    f_snap = binary.solve().f_gw
    nums = polytrope_numbers()
    print(f"snapshot f_gw = {f_snap:.2f} Hz")
    print(f"polytrope: l=2 k={nums[2]['k']:.5f} h={nums[2]['h']:.5f} w/w0={nums[2]['w']:.4f} | "
          f"l=3 k={nums[3]['k']:.5f} h={nums[3]['h']:.5f} w/w0={nums[3]['w']:.4f}")
    stars = []
    for name, spin in (("heavy", args.spin_heavy), ("light", args.spin_light)):
        s = star_block(name, nums, spin, f_snap)
        rep = TS.regime_report(to_model(s))
        print(f"\n{name}: spin {spin:.0f} Hz, r/R = {s['r_over_R']:.3f}, A_nl(l=2) = {s['A_nl_l2']:+.4f}")
        for r in rep["modes"]:
            if r["m"] > 0:
                print(f"   mode (l={r['l']}, m={r['m']:+d}): Delta/omega = {r['delta_over_omega']:+.3f}")
        print(f"   tide dR/R in [{rep['tide_range'][0]:+.3f}, {rep['tide_range'][1]:+.3f}], "
              f"dV/V = {rep['dV_tide']:+.4f}")
        for msg in rep["warnings"]:
            print(f"   WARNING: {msg}")
        if rep["errors"]:
            print("\n".join(f"   ERROR: {e}" for e in rep["errors"]))
            print(f"\nV11 failed for {name}: nothing written.")
            return 1
        stars.append(s)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    write_toml(args.out, stars, {
        "generator": "tools/make_star_modes.py",
        "model": "Gamma=2 Newtonian polytrope scaled per star; Paper 1/2 amplitudes via src/tidal_waveform.py",
        "f_gw_hz": f_snap})
    print(f"\nwrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
